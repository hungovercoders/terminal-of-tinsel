//! Builds the Terminal of Tinsel website: a static site with the home page,
//! the roster, a page for every creature, the advent calendar and the small
//! print. Everything about the creatures comes from the program's own
//! library, so the site can't drift from what the terminal shows.
//!
//! Run it from the repository root:
//!
//! ```bash
//! cargo run -p tinsel-site -- --out dist
//! ```

mod colour;
mod course;
mod html;
mod pages;

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use terminal_of_tinsel::creatures::{Creature, Vault};

pub use colour::{BACKGROUND, PANEL, contrast, readable};
pub use course::Course;
pub use html::esc;

/// Where the site will live. The canonical links, the sitemap and llms.txt
/// are built from it; `--base-url` overrides it for a preview.
pub const BASE_URL: &str = "https://terminaloftinsel.com/";

/// The repository, for the source, releases and contributing links.
pub const REPO: &str = "https://github.com/hungovercoders/terminal-of-tinsel";

/// The site's name, as it appears in titles.
pub const NAME: &str = "Terminal of Tinsel";

/// Where to write the site and what address it will be served from.
pub struct Config {
    pub out: PathBuf,
    pub base_url: String,
}

/// One page of the site, before it is wrapped in the shared shell.
pub struct Page {
    /// The path under the site's root, such as `creatures/krampus.html`.
    pub path: String,
    pub title: String,
    pub description: String,
    /// Which part of the site the page belongs to, for the navigation.
    pub section: &'static str,
    /// The creature whose colours the page wears, if any.
    pub theme: Option<String>,
    /// Whether the page is drawn as an engraving, as the Dickens pack is.
    pub engraving: bool,
    pub body: String,
}

impl Page {
    /// The prefix that takes a link on this page back to the site's root.
    /// The 404 page is served at whatever address was missing, at any depth,
    /// so it alone links from `/`.
    pub fn root(&self) -> String {
        if self.path == "404.html" {
            return "/".to_string();
        }
        "../".repeat(self.path.matches('/').count())
    }
}

/// Every page of the site, in the order they are written.
pub fn pages(vault: &Vault, course: &Course) -> Vec<Page> {
    let mut all = vec![
        pages::home(vault),
        pages::roster(vault),
        pages::advent(vault),
        pages::privacy(),
        pages::not_found(),
    ];
    all.extend((0..vault.creatures.len()).map(|i| pages::creature(vault, i)));
    all.extend(course.pages());
    all
}

/// Writes the whole site and returns how many HTML pages it made.
pub fn build(cfg: &Config) -> io::Result<usize> {
    let vault = Vault::load();
    let base = with_slash(&cfg.base_url);
    let course = Course::load(&manifest("../course"))?;
    let pages = pages(&vault, &course);
    for page in &pages {
        write(&cfg.out.join(&page.path), &html::shell(page, &base))?;
    }
    copy_dir(&manifest("static"), &cfg.out.join("static"))?;
    write(
        &cfg.out.join("static/themes.css"),
        &themes_css(&vault.creatures),
    )?;
    fs::copy(manifest("../public/_headers"), cfg.out.join("_headers"))?;
    write(&cfg.out.join("sitemap.xml"), &sitemap(&pages, &base))?;
    write(&cfg.out.join("robots.txt"), &robots(&base))?;
    write(
        &cfg.out.join("llms.txt"),
        &(llms_txt(&vault, &base) + &course.llms_txt(&base)),
    )?;
    Ok(pages.len())
}

/// A path beside this crate's manifest.
fn manifest(rel: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join(rel)
}

fn with_slash(url: &str) -> String {
    format!("{}/", url.trim_end_matches('/'))
}

fn write(path: &Path, text: &str) -> io::Result<()> {
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    fs::write(path, text)
}

fn copy_dir(from: &Path, to: &Path) -> io::Result<()> {
    fs::create_dir_all(to)?;
    for entry in fs::read_dir(from)? {
        let entry = entry?;
        let target = to.join(entry.file_name());
        if entry.file_type()?.is_dir() {
            copy_dir(&entry.path(), &target)?;
        } else {
            fs::copy(entry.path(), target)?;
        }
    }
    Ok(())
}

/// The class a creature's page and cards wear for its colours.
pub fn theme_class(id: &str) -> String {
    format!("c-{id}")
}

/// A class of colours for every creature. The site allows no inline
/// styles, so the colours a creature brings are written out here, lightened
/// where they would be hard to read on the dark background.
pub fn themes_css(creatures: &[Creature]) -> String {
    let mut css = String::from(
        "/* Generated by the site builder from each creature's theme. Don't edit. */\n",
    );
    for c in creatures {
        css.push_str(&format!(
            ".{} {{ --primary: {}; --accent: {}; }}\n",
            theme_class(&c.id),
            readable(&c.theme.primary),
            readable(&c.theme.accent),
        ));
    }
    css
}

/// Whether a page belongs in the sitemap and llms.txt.
fn listed(page: &Page) -> bool {
    page.path != "404.html"
}

fn sitemap(pages: &[Page], base: &str) -> String {
    let mut xml = String::from(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\n",
    );
    for page in pages.iter().filter(|p| listed(p)) {
        xml.push_str(&format!(
            "  <url><loc>{}</loc></url>\n",
            esc(&html::address(base, &page.path))
        ));
    }
    xml.push_str("</urlset>\n");
    xml
}

fn robots(base: &str) -> String {
    format!("User-agent: *\nAllow: /\n\nSitemap: {base}sitemap.xml\n")
}

/// A plain-text guide to the site for language models: what the program is
/// and a link to every creature.
pub fn llms_txt(vault: &Vault, base: &str) -> String {
    let mut text = format!(
        "# {NAME}\n\n> A command-line program about the creatures of Christmas folklore, presented by a fictional television host, Auntie Aerial, on Channel 25's Midwinter Special. It is free software, written in Rust, and the sister project of Terminal of Terror.\n\n## Pages\n\n- [Home]({base}): what the program does and how to install it\n- [The roster]({base}creatures/index.html): every creature, by pack\n- [The advent calendar]({base}advent.html): the guest behind each door from 1 to 24 December\n- [Privacy]({base}privacy.html): what the site collects, which is nothing\n- [Source]({REPO}): the code, the creature data and how to contribute\n"
    );
    for (pack, creatures) in vault.by_pack() {
        text.push_str(&format!("\n## {}\n\n{}\n\n", pack.name, pack.description));
        for c in creatures {
            text.push_str(&format!(
                "- [{}]({base}creatures/{}.html): {}\n",
                c.name, c.id, c.description
            ));
        }
    }
    text
}
